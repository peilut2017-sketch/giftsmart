import { createContext, useContext, useEffect, useState } from 'react'

export type LocaleContextValue = {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  dir: 'rtl' | 'ltr'
}

export const LocaleContext = createContext<LocaleContextValue>({
  locale: 'he',
  setLocale: () => {},
  t: (k) => k,
  dir: 'rtl',
})

/**
 * Standalone translator for non-component code (contexts, hooks, notification
 * builders) that has no access to useT(). Reads the active locale directly;
 * locale switches re-render the tree anyway, so values stay fresh where it
 * matters. Components should keep using useT().
 */
export function translate(key: string, vars?: Record<string, string | number>, forceLocale?: Locale): string {
  let loc: Locale = 'he'
  try { loc = forceLocale ?? ((localStorage.getItem('gs_locale') as Locale) || 'he') } catch { /* SSR/tests */ }
  let result: string
  if (loc === 'he') {
    result = translations[key] ?? key
  } else {
    result = translations[key + '.en'] ?? translations[key] ?? key
  }
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      result = result.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    })
  }
  return result
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    return (localStorage.getItem('gs_locale') as Locale) || 'he'
  })

  useEffect(() => {
    localStorage.setItem('gs_locale', locale)
    document.documentElement.setAttribute('lang', locale)
    document.body.setAttribute('dir', locale === 'he' ? 'rtl' : 'ltr')
  }, [locale])

  function setLocale(l: Locale) { setLocaleState(l) }

  function t(key: string, vars?: Record<string, string | number>): string {
    return translate(key, vars, locale)
  }

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t, dir: locale === 'he' ? 'rtl' : 'ltr' }}>
      {children}
    </LocaleContext.Provider>
  )
}

export function useT() {
  const ctx = useContext(LocaleContext)
  return { t: ctx.t, locale: ctx.locale, dir: ctx.dir }
}

export function useLocale() {
  return useContext(LocaleContext)
}
